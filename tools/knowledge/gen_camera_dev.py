#!/usr/bin/env python3
# Writes eval/dev_camera_set.mjs: one typed question per camera label, plus Dana's deer-scat misses.
import json, os, re, sys
REPO = sys.argv[1] if len(sys.argv) > 1 else os.path.abspath(os.path.join(os.path.dirname(__file__), "../.."))
classes = json.load(open(f"{REPO}/assets/camera_id/classes.json"))
notes = json.loads(re.search(r"CAMERA_NOTES = (\{.*?\});", open(f"{REPO}/symbolic/camera_notes.js").read(), re.S).group(1))
idx = {p["symbol"]: p for p in json.load(open(f"{REPO}/symbolic_memory/books_index.json"))["passages"]}
entries = {}
for line in open(f"{REPO}/symbolic/entries_data.js"):
    if line.startswith("export const ENTRIES = "):
        for e in json.loads(line[len("export const ENTRIES = "):].rstrip().rstrip(";")): entries[e["id"]] = e
items = []
def clean(t): return re.sub(r"\s*\([^)]*\)", "", t).strip()
for label, meta in classes.items():
    if meta.get("group") == "everyday": continue
    note = notes[label]
    name = clean(meta["title"])
    if note in entries:
        need = [entries[note]["title"].split(" (")[0]]
        if entries[note].get("call", "").find("1-800-222-1222") >= 0: need.append("1-800-222-1222")
    else:
        text = idx[note]["context"].lower()
        word = next((w for w in re.findall(r"[a-z']+", name.lower()) if len(w) > 3 and w in text), None)
        if not word: sys.exit(f"no checkable phrase for {label}")
        need = [word]
    items.append({"id": f"cam-{label.replace('_', '-')}", "category": "camera-label", "prompt": f"What is {name.lower()}?", "expect": {"kind": "facts", "all": need}})
extra = [
    ("cam-deer-scat-tell", "Tell me about deer scat", ["Deer scat", "pellets"]),
    ("cam-deer-scat-lower", "what is deer scat", ["Deer scat", "pellets"]),
    ("cam-deer-droppings", "What do deer droppings look like?", ["Deer scat", "pellets"]),
    ("cam-deer-poop", "Is this deer poop?", ["Deer scat"]),
    ("hunt-deer-rub", "What is a buck rub?", ["Deer rubs", "antlers"]),
    ("hunt-deer-scrape", "What is a deer scrape?", ["Deer scrapes", "licking branch"]),
    ("hunt-deer-tracks", "What do deer tracks look like?", ["Deer tracks", "heart"]),
    ("hunt-deer-sign", "How do I read deer sign?", ["Reading deer sign"]),
    ("cam-raccoon-latrine", "Is raccoon poop dangerous?", ["Raccoon scat", "roundworm"]),
]
for i, p, need in extra:
    items.append({"id": i, "category": "camera-label", "prompt": p, "expect": {"kind": "facts", "all": need}})
out = ["// Generated by the round-4 camera-note builder. Not the frozen v1 suite and not the external holdout.",
       "// One typed question for every camera-ID label, so a label the camera shows is also answered in Ask,",
       "// plus the deer-sign questions from Jeff's hunting list and Dana's \"Tell me about deer scat\" miss.",
       "export const CAMERA_DEV_SET = " + json.dumps(items, indent=1, ensure_ascii=False) + ";", ""]
open(f"{REPO}/eval/dev_camera_set.mjs", "w").write("\n".join(out))
print(len(items))
