// Writes symbolic/routing/regions.js and src/phone/route/route_asset_map.native.js from the built
// files in assets/routing. Run after build_all.sh:  node tools/routing/make_regions.mjs
import fs from "fs";
import path from "path";
import { readHeader } from "../../symbolic/routing/graph_format.js";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "../..");
const dir = path.join(root, "assets/routing");
const NAMES = { me: "Maine", ri: "Rhode Island", nh: "New Hampshire", vt: "Vermont", ma: "Massachusetts", ct: "Connecticut", ny: "New York", pa: "Pennsylvania", mi: "Michigan", wi: "Wisconsin", mn: "Minnesota", co: "Colorado", mt: "Montana", id: "Idaho", wy: "Wyoming" };
const regions = [];
for (const file of fs.readdirSync(dir).filter((f) => f.endsWith(".yrg")).sort()) {
  const id = file.replace(/\.yrg$/, "");
  const bytes = new Uint8Array(fs.readFileSync(path.join(dir, file)));
  const h = readHeader(bytes);
  const places = path.join(dir, `${id}.ypl`);
  regions.push({
    id,
    name: NAMES[id] || id,
    bounds: { south: +h.south.toFixed(4), west: +h.west.toFixed(4), north: +h.north.toFixed(4), east: +h.east.toFixed(4) },
    nodes: h.nodes,
    edges: h.edges,
    graphBytes: bytes.length,
    placeBytes: fs.existsSync(places) ? fs.statSync(places).size : 0
  });
}
const built = new Date().toISOString().slice(0, 10);
fs.writeFileSync(path.join(root, "symbolic/routing/regions.js"),
  `// Generated by tools/routing/make_regions.mjs. Do not edit by hand.\n// Offline road graphs and place lists bundled in the app, one per map-pack state.\n// Data: (c) OpenStreetMap contributors, ODbL 1.0 (Geofabrik extracts).\nexport const ROUTE_DATA_BUILT = ${JSON.stringify(built)};\nexport const ROUTE_REGIONS = ${JSON.stringify(regions, null, 2)};\n`);
const lines = regions.map((r) => `  ${JSON.stringify(r.id)}: { graph: require("../../../assets/routing/${r.id}.yrg"), places: require("../../../assets/routing/${r.id}.ypl") }`);
fs.mkdirSync(path.join(root, "src/phone/route"), { recursive: true });
fs.writeFileSync(path.join(root, "src/phone/route/route_asset_map.native.js"),
  `// Generated by tools/routing/make_regions.mjs. Do not edit by hand.\nexport const ROUTE_ASSETS = {\n${lines.join(",\n")}\n};\n`);
fs.writeFileSync(path.join(root, "src/phone/route/route_asset_map.js"),
  `// Generated by tools/routing/make_regions.mjs. The web build carries no offline road data.\nexport const ROUTE_ASSETS = {};\n`);
console.log(regions.map((r) => `${r.id} ${(r.graphBytes / 1e6).toFixed(1)}MB + ${(r.placeBytes / 1e6).toFixed(1)}MB`).join("\n"));
console.log("total MB", (regions.reduce((s, r) => s + r.graphBytes + r.placeBytes, 0) / 1e6).toFixed(1));
