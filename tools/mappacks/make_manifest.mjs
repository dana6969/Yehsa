// Writes symbolic/pack_manifest.js from the packs built by build_pack.py.
// Usage: node tools/mappacks/make_manifest.mjs <packs dir> [release tag]
// The manifest is bundled in the app, so the pack list shows with no signal.
import fs from "node:fs";
import crypto from "node:crypto";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const dir = process.argv[2] || "/workspace/yehsa-r3-packs";
const tag = process.argv[3] || "map-packs-2026-11";
const regions = JSON.parse(fs.readFileSync(path.join(here, "regions.json"), "utf8")).regions;

function md5(file) {
  const hash = crypto.createHash("md5");
  const fd = fs.openSync(file, "r");
  const buf = Buffer.alloc(1 << 20);
  for (;;) {
    const n = fs.readSync(fd, buf, 0, buf.length, null);
    if (!n) break;
    hash.update(buf.subarray(0, n));
  }
  fs.closeSync(fd);
  return hash.digest("hex");
}

const groupOf = (r) => (r.id.startsWith("me-") ? "Maine" : ["ri", "nh", "vt", "ma", "ct"].includes(r.id) ? "New England" : ["ny", "pa"].includes(r.id) ? "Northeast" : "More states");
const packs = [];
for (const region of regions) {
  const meta = path.join(dir, `${region.id}.json`);
  if (!fs.existsSync(meta)) continue;
  const info = JSON.parse(fs.readFileSync(meta, "utf8"));
  const file = path.join(dir, info.file);
  packs.push({
    id: info.id,
    name: info.name,
    region: info.region,
    group: groupOf(region),
    file: info.file,
    bytes: info.bytes,
    md5: md5(file),
    sha256: info.sha256,
    built: info.built,
    bounds: info.bounds,
    minZoom: info.minZoom,
    maxZoom: info.maxZoom,
    tilePx: info.tilePx,
    license: info.license,
    attribution: info.attribution
  });
}
const manifest = {
  schema: 1,
  releaseTag: tag,
  baseUrl: `https://github.com/dana6969/Yehsa/releases/download/${tag}/`,
  note: "Built by tools/mappacks/build_pack.py. Terrain, land cover, water, trails, place names. No road layer. No parcel or owner layer.",
  packs
};
const out = path.join(here, "..", "..", "symbolic", "pack_manifest.js");
fs.writeFileSync(out, `// Generated by tools/mappacks/make_manifest.mjs. Do not edit by hand.\nexport const PACK_MANIFEST = ${JSON.stringify(manifest, null, 2)};\n`);
console.log(`wrote ${out} with ${packs.length} packs, ${(packs.reduce((s, p) => s + p.bytes, 0) / 1e6).toFixed(0)} MB`);
