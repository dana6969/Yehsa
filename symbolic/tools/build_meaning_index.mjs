// Build the offline meaning index that ships with Yehsa.
//   node symbolic/tools/build_meaning_index.mjs            notes + prototypes + scripture
//   node symbolic/tools/build_meaning_index.mjs --notes    notes + prototypes only
// Needs the bundled model at assets/meaning/ and the dev dependency onnxruntime-node.
// Output: symbolic/meaning/notes_index.js, assets/meaning/scripture.i8, symbolic/meaning/scripture_meta.js

import crypto from "crypto";
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import { sourceKind } from "../book_search.js";
import { MODEL_INFO } from "../meaning/embedder.js";
import { loadNodeEmbedder, MODEL_PATH } from "../meaning/embed_node.js";
import { fnv1a } from "../meaning/hash.js";
import { bytesToBase64, packIndex, quantize } from "../meaning/int8_index.js";
import { fieldNotes } from "../meaning/note_corpus.js";
import { noteDocument } from "../meaning/meaning_layer.js";
import { EMERGENCY_PROTOTYPES, INTENT_PROTOTYPES } from "../meaning/prototypes.js";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const notesOnly = process.argv.includes("--notes");

const embedder = await loadNodeEmbedder();
if (!embedder) throw new Error(`meaning model not found or onnxruntime-node missing (${MODEL_PATH})`);
const modelSha256 = crypto.createHash("sha256").update(fs.readFileSync(MODEL_PATH)).digest("hex");

const notes = fieldNotes().map((note) => ({
  symbol: note.symbol,
  source: note.source,
  kind: sourceKind(note.source),
  hash: fnv1a(note.text),
  text: note.text
}));
const noteVectors = await embedder.embed(notes.map(noteDocument), { maxLength: MODEL_INFO.passageMaxTokens, batchSize: 8 });

const intentLabels = [];
const intentTexts = [];
for (const [label, list] of Object.entries(INTENT_PROTOTYPES)) {
  for (const text of list) {
    intentLabels.push(label);
    intentTexts.push(text);
  }
}
const intentVectors = await embedder.embed(intentTexts, { maxLength: MODEL_INFO.queryMaxTokens });
const emergencyVectors = await embedder.embed(EMERGENCY_PROTOTYPES, { maxLength: MODEL_INFO.queryMaxTokens });

const pack = (vectors) => bytesToBase64(packIndex(quantize(vectors)));
const payload = {
  model: MODEL_INFO.name,
  modelFile: MODEL_INFO.file,
  modelSha256,
  dims: MODEL_INFO.dims,
  notes,
  noteVectors: pack(noteVectors),
  intentLabels,
  intentVectors: pack(intentVectors),
  emergencyCount: EMERGENCY_PROTOTYPES.length,
  emergencyVectors: pack(emergencyVectors)
};
const header = "// Generated by symbolic/tools/build_meaning_index.mjs. Do not edit by hand.\n// int8 sentence vectors of the approved field notes and the routing prototypes.\n";
fs.writeFileSync(path.join(ROOT, "symbolic/meaning/notes_index.js"), `${header}export default ${JSON.stringify(payload)};\n`);
console.log(`notes ${notes.length}, intent prototypes ${intentLabels.length}, emergency prototypes ${EMERGENCY_PROTOTYPES.length}`);

if (!notesOnly) {
  const indexPath = path.join(ROOT, "symbolic_memory/spiritual_index.json");
  const raw = fs.readFileSync(indexPath, "utf8");
  const passages = JSON.parse(raw).passages;
  const started = Date.now();
  const vectors = [];
  const step = 512;
  for (let i = 0; i < passages.length; i += step) {
    const slice = passages.slice(i, i + step).map((passage) => passage.text);
    vectors.push(...await embedder.embed(slice, { maxLength: 128, batchSize: 32 }));
    process.stderr.write(`scripture ${Math.min(i + step, passages.length)}/${passages.length}\r`);
  }
  const bytes = packIndex(quantize(vectors));
  fs.writeFileSync(path.join(ROOT, "assets/meaning/scripture.i8"), bytes);
  const meta = {
    rows: passages.length,
    sourceSha256: crypto.createHash("sha256").update(raw).digest("hex"),
    bytes: bytes.length
  };
  fs.writeFileSync(path.join(ROOT, "symbolic/meaning/scripture_meta.js"), `${header}export default ${JSON.stringify(meta)};\n`);
  console.log(`\nscripture ${passages.length} rows, ${bytes.length} bytes, ${Math.round((Date.now() - started) / 1000)} s`);
}
