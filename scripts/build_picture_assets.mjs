// Writes symbolic/picture_assets.native.js and symbolic/picture_assets.web.js from assets/pictures/manifest.json.
// Metro only bundles images it can see as static require() calls, so every picture gets one line.
// Run after adding or removing a picture: node scripts/build_picture_assets.mjs
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const manifest = JSON.parse(fs.readFileSync(path.join(root, "assets/pictures/manifest.json"), "utf8"));
const present = [];
const missing = [];
for (const image of manifest.images || []) {
  if (!image.file) continue;
  if (fs.existsSync(path.join(root, "assets/pictures", image.file))) present.push(image.file);
  else missing.push(image.file);
}
const lines = [...new Set(present)].sort().map((file) => `  ${JSON.stringify(file)}: require(${JSON.stringify(`../assets/pictures/${file}`)})`);
const body = `// Generated by scripts/build_picture_assets.mjs. Do not edit by hand.
// Static require() calls so Metro bundles every picture into the app.

export const PICTURE_ASSETS = {
${lines.join(",\n")}
};

export function pictureSource(file) {
  return (file && PICTURE_ASSETS[file]) || null;
}
`;
for (const name of ["picture_assets.native.js", "picture_assets.web.js"]) {
  fs.writeFileSync(path.join(root, "symbolic", name), body);
}
console.log(`picture assets: ${present.length} bundled, ${missing.length} missing${missing.length ? `: ${missing.join(", ")}` : ""}`);
